"""Task A (spec S5): harden ForwardMaterialTrace611's validation WITHOUT
making the tracker more complex. Does NOT retune the frozen rule
(Jaccard >= 0.30, from material_identity_step2_20260921). This script only
TESTS it, harder, than Step 2's own cross-episode-unrelated-pair calibration
did.

Two natural-data splits, disjoint by EPISODE (never by row), both under the
identical PRIMARY regime as the frozen rule's own calibration data:

  DEV / already-used-for-calibration : data/observational_corpus_611__val.npz
      seeds 236-247 (12 episodes). This is the exact corpus
      calibrate_identity_rule.py used to select Jaccard>=0.30. Re-analyzed
      here with a HARDER negative construction (same-episode, same-frame
      distractors instead of cross-episode pairs), but the threshold itself
      is never touched.

  UNTOUCHED VALIDATION : data/observational_corpus_611__test.npz
      seeds 248-259 (12 episodes). Generated by observational_corpus_611.py
      at the same primary regime, but never read by ANY prior Step-1/Step-2
      script (grep-verified: only *_611.py training/predictive-model code
      and this script touch this file). This is the genuine held-out set
      task S5.2 asks for -- no new simulation needed, the file already
      existed on disk from the predictive-model corpus build.

Two analyses, per split:

(1) SAME-FRAME HARD NEGATIVES (S5.1). Step 2's own calibration negatives
    were candidates drawn from DIFFERENT episodes -- an easy case (different
    random initial condition, likely different region of state space
    entirely). The real adversarial case is a distractor candidate
    co-present in the SAME episode, SAME transition (t -> t+1): another
    flock, a spatially nearby group, a split daughter, a candidate that
    overlaps partially. For every candidate c at (episode, t) with
    len(c)>=5, and its own best-Jaccard match at t+1 (the "presumed
    continuation" -- what a tracker actually chasing this candidate would
    compare against), every OTHER candidate at t+1 is a hard negative
    against c. Categorized (never silently labelled "ground truth
    negative"):
      - zero_overlap: jaccard==0 with c -- the only case this pass calls
        "obvious unrelated" (no material relationship at this transition).
      - nonzero_below_threshold: 0 < jaccard < 0.30.
      - AT_OR_ABOVE_THRESHOLD: jaccard >= 0.30 -- the dangerous case: an
        unrelated (non-chosen) same-frame candidate that the frozen rule
        would itself also accept, had it been offered as the only
        candidate. This is the number Step 2's cross-episode-only
        calibration could not see.
    Stratified by target size bucket and by spatial proximity (torus-aware
    centroid distance at t+1, bucketed relative to the episode's own local
    density scale, geometry_611.local_scale -- never the true interaction
    radius).

(2) EPISODE-LEVEL SEQUENTIAL TRACE AUDIT (S5.3). ForwardMaterialTrace611
    run forward, full episode, from several seed targets per episode
    (largest 3 candidates at t=5, skipping the very first few detector-
    warmup steps). No control, no target heading, no outcome -- pure
    identity behaviour on natural data. Per trace: final status, number of
    unresolved episodes and their durations, number of recoveries, number
    of split/merge flags, cumulative turnover (1 - jaccard(members at
    trace-start, members at trace-end)), max duration reached.
    "Erroneous transfer" cannot be scored against an omniscient ground-truth
    label (none exists for real simulated flocks -- this pass does not
    invent one). Instead this pass reports the rule's own internal
    consistency signals -- because ForwardMaterialTrace611 structurally
    cannot accept a step whose jaccard-to-previous is below threshold, a
    "false switch" can only happen at the moment of an accepted step: this
    pass separately reports, at every accepted continuing step, the JACCARD
    MARGIN between the winning candidate and the runner-up (if any other
    candidate also passed the gate) -- a small margin is a risk signal for
    ambiguity, not proof of a wrong choice.
"""
